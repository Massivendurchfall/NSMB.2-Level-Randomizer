"""Turns the memory measurements from the emulator into plugin/Includes/MemoryTable.hpp.

    python make_memory_table.py <measurement files...> <MemoryTable.hpp>

Input are the lines emu_measure.ps1 wrote for the cases of make_measure_cases.py:
  level=..;addkind=0;addkind=K | ActorHeap N | ...          a level with one more kind loaded
  level=..;area=A.. # W-N area A key KKKKKKKK | ActorHeap N  an untouched level, started in area A
The cost of a kind is what it takes away compared to the same level without it, the highest
value over the base levels. The room of a level is the lowest free value over its areas.
"""
import os
import re
import sys

POOLS = ('ActorHeap', 'ModelResourceHeap', 'ModelSetupHeap', 'AreaHeap', 'VRAMA', 'VRAMB')
NAMES = ('MEM_ACTOR', 'MEM_MODEL', 'MEM_SETUP', 'MEM_AREA', 'MEM_VRAM_A', 'MEM_VRAM_B')

core = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'plugin', 'Sources', 'Randomizer.cpp'),
            encoding='utf-8').read()
kind_names = {int(i): n for i, n in re.findall(r'\{\s*(\d+), SLOT_\w+,.*?"([^"]+)" \}', core)}
kind_names[252] = 'Item spawner, for the item rain'

baseline = {}       # base level -> values
with_kind = {}      # (base level, kind) -> values
areas = {}          # key -> {(name, area): values}
problems = []

for path in sys.argv[1:-1]:
    for line in open(path, encoding='latin1'):
        line = line.strip()
        if not line:
            continue
        label, _, rest = line.partition(' | ')
        values = {}
        for pool in POOLS:
            m = re.search(r'\b%s (\d+)' % pool, rest)
            if m:
                values[pool] = int(m.group(1))
        level = int(re.search(r'level=(\d+)', label).group(1))
        tag = re.search(r'# (\S+) area (\d) key ([0-9A-F]{8})', label)
        kinds = [int(k) for k in re.findall(r'addkind=(\d+)', label) if k != '0']
        if len(values) != len(POOLS):
            problems.append(line)
            if tag:
                areas.setdefault(int(tag.group(3), 16), {})[(tag.group(1), int(tag.group(2)))] = None
            continue
        if tag:
            areas.setdefault(int(tag.group(3), 16), {})[(tag.group(1), int(tag.group(2)))] = values
        elif kinds:
            with_kind[(level, kinds[0])] = values
        else:
            baseline[level] = values


def kb_up(n):
    return (n + 1023) // 1024


costs = {}
for (level, kind), values in sorted(with_kind.items()):
    if level not in baseline:
        continue
    cost = [max(0, baseline[level][p] - values[p]) for p in POOLS]
    old = costs.get(kind, [0] * len(POOLS))
    costs[kind] = [max(a, b) for a, b in zip(old, cost)]

rooms = {}
for key, per_area in sorted(areas.items()):
    name = sorted(per_area)[0][0]
    if any(v is None for v in per_area.values()):
        problems.append('%s: an area could not be measured, level left out' % name)
        continue
    if not any(area == 1 for _n, area in per_area):
        continue
    free = [min(v[p] for v in per_area.values()) // 1024 for p in POOLS]
    both = min(v['VRAMA'] + v['VRAMB'] for v in per_area.values()) // 1024
    rooms[key] = (name, free, both, len(per_area))

out = []
out.append('// Generated by tools/make_memory_table.py from measurements in the emulator, do not edit.')
out.append('// %d kinds, %d levels.' % (len(costs), len(rooms)))
out.append('#ifndef MEMORYTABLE_HPP')
out.append('#define MEMORYTABLE_HPP')
out.append('')
out.append('#include <cstdint>')
out.append('')
out.append('#include "Randomizer.hpp"')
out.append('')
out.append('namespace Rando')
out.append('{')
out.append('    // What loading one more kind of enemy takes from each memory pool of the game, in KB.')
out.append('    // Order of the values: ' + ', '.join(NAMES))
out.append('    struct KindCost')
out.append('    {')
out.append('        uint16_t    id;')
out.append('        uint16_t    cost[MEM_COUNT];')
out.append('    };')
out.append('')
out.append('    // What an untouched level leaves free in each pool, in KB: the lowest value of its areas,')
out.append('    // read a few seconds after the area has loaded. both is the lowest sum of the VRAM banks.')
out.append('    struct LevelRoom')
out.append('    {')
out.append('        uint32_t    key;        // CRC of the course file of the first area')
out.append('        uint16_t    free[MEM_COUNT];')
out.append('        uint16_t    both;')
out.append('    };')
out.append('')
out.append('    const KindCost  kKindCosts[] =')
out.append('    {')
for kind, cost in sorted(costs.items()):
    out.append('        { %3d, { %s } },   // %s' % (kind, ', '.join('%4d' % kb_up(c) for c in cost),
                                                    kind_names.get(kind, '?')))
if not costs:
    out.append('        { 0, { 0, 0, 0, 0, 0, 0 } },')
out.append('    };')
out.append('    const uint32_t  kKindCostCount = %d;' % len(costs))
out.append('')
out.append('    const LevelRoom kLevelRooms[] =')
out.append('    {')
for key, (name, free, both, count) in sorted(rooms.items(), key=lambda kv: [int(x) for x in kv[1][0].split('-')]):
    out.append('        { 0x%08X, { %s }, %4d },   // %s, %d areas'
               % (key, ', '.join('%4d' % f for f in free), both, name, count))
if not rooms:
    out.append('        { 0, { 0, 0, 0, 0, 0, 0 }, 0 },')
out.append('    };')
out.append('    const uint32_t  kLevelRoomCount = %d;' % len(rooms))
out.append('}')
out.append('')
out.append('#endif')
open(sys.argv[-1], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('%d kinds, %d levels, %d lines with problems' % (len(costs), len(rooms), len(problems)))
for p in problems[:30]:
    print('  problem:', p[:150])
